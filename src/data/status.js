// Статусы-ДоТы на врагах (src/behaviors/status.js). Оружие вешает их полем status (weapons.js):
//   status: { type: 'poison' | 'burning' | 'bleeding', chance: 0..1, share?: доля удара (иначе из типа) }
// на всём оружии или в уровне (уровень главнее). Шанс тянется из RNG сима на каждый удар (при chance < 1).
//
// Урон ДоТа = share × урон удара (уже × attack/magic владельца и множители уникалок, но до крита), разложенный
// на duration секунд тиками по DOT.tick. Тики не критуют, не отбрасывают и не будят шипы; урон идёт в статистику
// того оружия, что наложило статус (DPS в HUD, итоги, телеметрия), тип урона — dmgType этого оружия.
// Отдельного стата урона ДоТов нет: ДоТ растёт только вместе с уроном удара.
//
// Стакание как в PoE:
//   poison  — 'stack': каждый удар добавляет свой стак со своим таймером, стаки суммируются, не больше maxStacks
//             (при полном наборе новый заменяет стак, которому осталось меньше всего);
//   burning — 'strongest': один ожог, остаётся сильнейший по урону за тик, таймер обновляется каждым наложением;
//   bleeding — 'strongest', как ожог; вешают только удары ближнего боя (melee_arc, slash, проверяет tests/unit/status.test.js);
//   chill   — 'slow': ДоТ без урона, только замедление (скорость × slow на duration с, сильнее и дольше из
//             действующего и нового, боссы иммунны ко всем статусам). В поле status оружия
//             можно задать свои slow и duration: { type: 'chill', chance, slow: 0.5, duration: 1.2 }.
//
// Почему числа такие. В PoE ДоТ — основной урон билда, его качают отдельными статами: PoE1 ignite 90%/с × 4 с
// (360% удара), poison 30%/с × 2 с (60%), bleed 70%/с × 5 с (350%); PoE2 ignite 20%/с × 4 с (80%), poison
// 20%/с × 2 с (40%, стаки без лимита), bleed 15%/с × 5 с (75%). У нас ДоТ только приправа к удару, без своего
// стата, поэтому суммарно 30–40% удара за 2–3 с — около половины PoE2:
//   poison 30% за 3 с (6 тиков по 5%): облако бьёт раз в 0.5 с с шансом 1, в облаке набирается ~6 стаков,
//     это +30% к урону облака, пока враг в нём, и хвост 3 с после выхода;
//   burning 40% за 2 с: не стакается, поэтому доля выше; шанс 0.3–0.5 у огненных оружий;
//   bleeding 30% за 3 с: ближний бой и так бьёт сильнее всех (docs/BALANCE_AUDIT.md 6.4), шанс 0.25.
