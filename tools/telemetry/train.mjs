import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { inspect } from 'node:util';
import { createHash } from 'node:crypto';
import { normalizeRun, parseCard } from './data.mjs';
import { cardFeatures, linearScore, probabilities } from '../simulation/features.mjs';

export function samplesFor(run) {
  return run.decisions.filter((d) => d.act === 'take' && d.offered.length > 1 &&
    d.offered.includes(d.chosen)).map((d) => ({
    features: d.offered.map((s) => cardFeatures(parseCard(s), d.context, d.lastTake)),
    target: d.offered.indexOf(d.chosen), cards: d.offered.map(parseCard),
  }));
}
export function fit(groups, epochs = 160) {
  const weights = {};
  const step = 0.65;
  for (let epoch = 0; epoch < epochs; epoch++) {
    const gradient = {};
    for (const samples of groups) {
      for (const sample of samples) {
        const probs = probabilities(sample.features.map((f) => linearScore(f, weights)));
        sample.features.forEach((f, i) => {
          const err = ((i === sample.target ? 1 : 0) - probs[i]) /
            (Math.max(1, samples.length) * groups.length);
          for (const [k, v] of Object.entries(f)) gradient[k] = (gradient[k] || 0) + err * v;
        });
      }
    }
    for (const [k, g] of Object.entries(gradient)) {
      weights[k] = (weights[k] || 0) + step * (g - 0.005 * (weights[k] || 0));
    }
  }
  return weights;
}
function evaluate(samples, score) {
  let loss = 0;
  let correct = 0;
  for (const s of samples) {
    const probs = probabilities(s.features.map((f, i) => score(f, i, s)));
    loss -= Math.log(Math.max(1e-12, probs[s.target]));
    if (probs.indexOf(Math.max(...probs)) === s.target) correct++;
  }
  return { n: samples.length, logLoss: loss / Math.max(1, samples.length),
    accuracy: correct / Math.max(1, samples.length) };
}
export function crossValidate(runs) {
  const groups = runs.map(samplesFor);
  return groups.map((test, index) => {
    const weights = fit(groups.filter((_, i) => i !== index &&
      (!runs[index].session || runs[i].session !== runs[index].session)));
    return { run: runs[index].id, learned: evaluate(test, (f) => linearScore(f, weights)),
      uniform: evaluate(test, () => 0), first: evaluate(test, (_, i) => i === 0 ? 3 : 0),
      legacy: evaluate(test, (f, i, s) => {
        const c = s.cards[i];
        const passive = { attack: 4, haste: 3.5, max_hp: 3, armor: 3, resistance: 3, regen: 2.5,
          speed: 2.5, crit: 2.5, pickup: 2, luck: 1 };
        const pref = { blade_arc: 1, storm_chain: 0.9, throwing_daggers: 0.8,
          guardian_shields: 0.7, war_axe: 0.5, firebomb: 0.5, holy_ground: 0.1 };
        return c.kind === 'weapon' ? (f.upgrade ? 5 : f.crowdedWeapon >= 4 / 6 ? 2 : 6) +
          (pref[c.id] || 0) : passive[c.id] || 2;
      }) };
  });
}

const source = process.argv[2] || 'tests/fixtures/telemetry';
const raw = await readFile(`${source}/runs.json`, 'utf8');
const manifest = JSON.parse(await readFile(`${source}/manifest.json`, 'utf8'));
if (createHash('sha256').update(raw).digest('hex') !== manifest.sha256) {
  throw new Error('dataset checksum mismatch');
}
const runs = JSON.parse(raw).map((r, i) => normalizeRun(r.run, i));
if (new Set(runs.map((r) => r.session || r.id)).size < 2) {
  throw new Error('Need at least two independent sessions for validation');
}
const cv = crossValidate(runs);
const metrics = Object.fromEntries(['learned', 'uniform', 'first', 'legacy'].map((key) => {
  const mean = (f) => cv.reduce((s, row) => s + row[key][f], 0) / cv.length;
  return [key, { runMeanLogLoss: mean('logLoss'), runMeanAccuracy: mean('accuracy') }];
}));
const voluntary = runs.flatMap((r) => r.decisions).filter((d) => d.voluntary &&
  ['take', 'skip', 'reroll', 'banish'].includes(d.act));
const counts = Object.fromEntries(['take', 'skip', 'reroll', 'banish'].map((act) =>
  [act, voluntary.filter((d) => d.act === act).length]));
const model = { version: `human-${manifest.sha256.slice(0, 12)}`, dataset: manifest.sha256,
  weights: fit(runs.map(samplesFor)), actionRates: Object.fromEntries(Object.entries(counts)
    .map(([k, v]) => [k, v / Math.max(1, voluntary.length)])),
  limitations: ['small run-level sample', 'legacy movement unavailable',
    'duo unvalidated', 'item preferences depend on this dataset'] };
await mkdir('tools/out/simulation', { recursive: true });
await writeFile('tools/simulation/model.mjs',
    `// Generated by telemetry:train; dataset checksum fixes provenance.\nexport const MODEL = ${inspect(model, { depth: null, compact: false, breakLength: 90 })};\n`);
await writeFile('tests/fixtures/telemetry/validation.json', JSON.stringify({ dataset: manifest.sha256,
  split: 'leave-one-run-out', nRuns: runs.length, metrics, folds: cv,
  warnings: runs.map((r) => ({ run: r.id, warnings: r.warnings })),
  counts: { picks: runs.reduce((s, r) => s + r.decisions.length, 0),
    snapshots: runs.reduce((s, r) => s + r.snapshots.length, 0), voluntary: counts },
  gate: metrics.learned.runMeanLogLoss < metrics.uniform.runMeanLogLoss &&
    metrics.learned.runMeanLogLoss < metrics.legacy.runMeanLogLoss }, null, 2) + '\n');
console.log(JSON.stringify({ model: model.version, metrics, counts }, null, 2));
