// Generate a content-addressed runtime revision without a self-referential Git SHA.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
const paths = [];
async function visit(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = `${dir}/${e.name}`;
    if (e.isDirectory()) await visit(p);
    else if (p.endsWith('.js') && p !== 'src/data/build.js') paths.push(p);
  }
}
await visit('src');
const hash = createHash('sha256');
for (const p of paths.sort()) hash.update(p).update(await readFile(p));
const content = `// Generated by npm run build:manifest; excludes this file from the hash.\nexport const BUILD = { source: '${hash.digest('hex')}' };\n`;
if (process.argv.includes('--check')) {
  if (await readFile('src/data/build.js', 'utf8') !== content) {
    throw new Error('Runtime revision is stale; run npm run build:manifest');
  }
} else await writeFile('src/data/build.js', content);
